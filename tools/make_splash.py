#!/usr/bin/env python3
"""Build the boot picture the sketch can actually hold.

A full 466x466 RGB565 frame is 434 KB. With the rest of the sketch that
overflows the 1.25 MB app slot (the maximum Arduino reports when the
board menu is not on the 3 MB scheme). The glass still gets 466 pixels:
the stored frame is 233x233 and the board doubles each pixel.

    python3 tools/make_splash.py [source.png]

Default source is docs/splash-src.png. A larger file is fitted to the
466 circle first. docs/splash.png is the doubled picture the glass shows.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_PNG = os.path.join(ROOT, "docs", "splash-src.png")
OUT_PNG = os.path.join(ROOT, "docs", "splash.png")
OUT_C = os.path.join(ROOT, "arduino_src", "splash_565.c")
OUT_H = os.path.join(ROOT, "arduino_src", "splash_565.h")
PANEL = 466
STORED = PANEL // 2  # 233. Doubled on the glass.


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | ((b & 0xF8) >> 3)


def fit_panel(src):
    im = src.convert("RGB")
    if im.size != (PANEL, PANEL):
        im = im.resize((PANEL, PANEL), Image.Resampling.LANCZOS)
    px = im.load()
    c = PANEL // 2
    r2 = c * c
    for y in range(PANEL):
        dy = y - c
        for x in range(PANEL):
            dx = x - c
            if dx * dx + dy * dy > r2:
                px[x, y] = (0, 0, 0)
    return im


def write_c(half):
    px = half.load()
    with open(OUT_C, "w") as f:
        f.write("/* Generated by tools/make_splash.py.\n"
                " * %dx%d RGB565. The board draws each pixel as a 2x2 block\n"
                " * so the glass still gets a %d circle. A full-size frame\n"
                " * does not fit the 1.25 MB app slot. */\n"
                "#include <stdint.h>\n"
                "#include \"splash_565.h\"\n"
                "\n"
                "const uint16_t splash_565[SPLASH_W * SPLASH_H] = {\n"
                % (STORED, STORED, PANEL))
        n = 0
        for y in range(STORED):
            for x in range(STORED):
                r, g, b = px[x, y]
                f.write("0x%04X," % rgb565(r, g, b))
                n += 1
                f.write("\n" if n % 12 == 0 else " ")
        if n % 12 != 0:
            f.write("\n")
        f.write("};\n")
    with open(OUT_H, "w") as f:
        f.write("/* Generated by tools/make_splash.py. The boot picture. */\n"
                "#ifndef SPLASH_565_H\n"
                "#define SPLASH_565_H\n"
                "\n"
                "#include <stdint.h>\n"
                "\n"
                "#define SPLASH_W %d\n"
                "#define SPLASH_H %d\n"
                "\n"
                "extern const uint16_t splash_565[SPLASH_W * SPLASH_H];\n"
                "\n"
                "#endif\n" % (STORED, STORED))


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else SRC_PNG
    panel = fit_panel(Image.open(src_path))
    if src_path != SRC_PNG:
        panel.save(SRC_PNG)
    half = panel.resize((STORED, STORED), Image.Resampling.LANCZOS)
    shown = half.resize((PANEL, PANEL), Image.Resampling.NEAREST)
    shown.save(OUT_PNG)
    write_c(half)
    print("stored %d bytes, glass %dx%d" % (STORED * STORED * 2, PANEL, PANEL))


if __name__ == "__main__":
    main()
