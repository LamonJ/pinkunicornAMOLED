#!/usr/bin/env python3
"""Turn docs/splash.png into the boot picture the panel draws.

The glass is a 466 circle. A larger source is scaled to fill that square,
then pixels outside the circle become black. The sketch stores the result
as RGB565, the same packing gfx_blit565 uses.

    python3 tools/make_splash.py [source.png]

Default source is docs/splash.png. A bigger file is scaled once; running
again on the 466 result does not scale it a second time.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PNG = os.path.join(ROOT, "docs", "splash.png")
OUT_C = os.path.join(ROOT, "arduino_src", "splash_565.c")
OUT_H = os.path.join(ROOT, "arduino_src", "splash_565.h")
SIDE = 466
CENTER = SIDE // 2
RADIUS2 = CENTER * CENTER


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | ((b & 0xF8) >> 3)


def fit(src):
    im = src.convert("RGB")
    if im.size != (SIDE, SIDE):
        im = im.resize((SIDE, SIDE), Image.Resampling.LANCZOS)
    px = im.load()
    for y in range(SIDE):
        dy = y - CENTER
        for x in range(SIDE):
            dx = x - CENTER
            if dx * dx + dy * dy > RADIUS2:
                px[x, y] = (0, 0, 0)
    return im


def write_c(im):
    px = im.load()
    with open(OUT_C, "w") as f:
        f.write("/* Generated by tools/make_splash.py from docs/splash.png.\n"
                " * 466x466 RGB565, black outside the round glass. */\n"
                "#include <stdint.h>\n"
                "#include \"splash_565.h\"\n"
                "\n"
                "const uint16_t splash_565[SPLASH_W * SPLASH_H] = {\n")
        n = 0
        for y in range(SIDE):
            for x in range(SIDE):
                r, g, b = px[x, y]
                f.write("0x%04X," % rgb565(r, g, b))
                n += 1
                f.write("\n" if n % 12 == 0 else " ")
        if n % 12 != 0:
            f.write("\n")
        f.write("};\n")
    with open(OUT_H, "w") as f:
        f.write("/* Generated by tools/make_splash.py. The boot picture. */\n"
                "#ifndef SPLASH_565_H\n"
                "#define SPLASH_565_H\n"
                "\n"
                "#include <stdint.h>\n"
                "\n"
                "#define SPLASH_W %d\n"
                "#define SPLASH_H %d\n"
                "\n"
                "extern const uint16_t splash_565[SPLASH_W * SPLASH_H];\n"
                "\n"
                "#endif\n" % (SIDE, SIDE))


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else OUT_PNG
    im = fit(Image.open(src_path))
    im.save(OUT_PNG)
    write_c(im)
    print("wrote %s and %s (%d pixels)" % (OUT_PNG, OUT_C, SIDE * SIDE))


if __name__ == "__main__":
    main()
